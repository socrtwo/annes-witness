// Writes docs/COMMANDS.md: which planned commands are implemented. Run: npm run catalog
// @ts-expect-error jsdom ships no type declarations
import { JSDOM } from 'jsdom';
import { writeFileSync } from 'node:fs';

const dom = new JSDOM('<!doctype html><html><body></body></html>', { url: 'http://localhost/' });
Object.assign(globalThis, { window: dom.window, document: dom.window.document, localStorage: dom.window.localStorage, HTMLElement: dom.window.HTMLElement, Node: dom.window.Node });

const reg = await import('../src/ui/registry');
(await import('../src/ui/cmd-file')).registerFileCommands();
(await import('../src/ui/cmd-case')).registerCaseCommands();
(await import('../src/ui/cmd-check')).registerCheckCommands();
(await import('../src/ui/cmd-ai')).registerAiCommands();

const all = reg.allCommands();
const done = all.filter((c) => reg.isRegistered(c.id));
const out: string[] = [
  '# Commands',
  '',
  `> **Generated by \`npm run catalog\`.** ${done.length} of ${all.length} planned commands are implemented in this version. A command is registered only when it works; the rest appear in the interface marked as planned. The full plan, with notes and origins, is in [COMMANDS-PLAN.md](COMMANDS-PLAN.md).`,
  '',
];
for (const t of reg.PLAN.tabs) {
  const cmds = t.groups.flatMap((g) => g.commands);
  const n = cmds.filter((c) => reg.isRegistered(c.id)).length;
  out.push(`## ${t.name} (${n} of ${cmds.length})`, '', '| Command | Id | Shortcut | State |', '|---|---|---|---|');
  for (const c of cmds) out.push(`| ${c.label} | \`${c.id}\` | ${c.shortcut ? `\`${c.shortcut}\`` : ''} | ${reg.isRegistered(c.id) ? 'implemented' : 'planned'} |`);
  out.push('');
}
writeFileSync(new URL('../docs/COMMANDS.md', import.meta.url), out.join('\n'));
console.log(`docs/COMMANDS.md: ${done.length} of ${all.length} implemented`);
console.log('planned:', all.filter((c) => !reg.isRegistered(c.id)).map((c) => c.id).join(' '));
